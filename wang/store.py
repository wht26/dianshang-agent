"""Anonymous local chat sessions, separate from v0.3 business data."""

import hashlib
import json
import secrets
import time
from .database import Database


class Store(Database):
    def __init__(self, dsn=None):
        super().__init__(dsn)
        self.initialize('\n            CREATE TABLE IF NOT EXISTS qa_sessions (digest TEXT PRIMARY KEY, created DOUBLE PRECISION);\n            CREATE TABLE IF NOT EXISTS qa_turns (\n                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n                session TEXT NOT NULL, question TEXT, answer TEXT, sources TEXT, mode TEXT,\n                created DOUBLE PRECISION, product_id TEXT);\n        ')

    @staticmethod
    def digest(token):
        return hashlib.sha256(token.encode()).hexdigest()

    def session(self, token):
        if token and len(token) <= 100:
            with self.db() as db:
                if db.execute("SELECT 1 FROM qa_sessions WHERE digest=%s", (self.digest(token),)).fetchone():
                    return token
        token = secrets.token_urlsafe(32)
        with self.db() as db:
            db.execute("INSERT INTO qa_sessions VALUES (%s,%s)", (self.digest(token), time.time()))
        return token

    def history(self, token, limit=20):
        with self.db() as db:
            rows = db.execute("SELECT question,answer,sources,mode,product_id FROM qa_turns WHERE session=%s "
                              "ORDER BY id DESC LIMIT %s", (self.digest(token), limit)).fetchall()
        return [{"question": row["question"], "answer": row["answer"],
                 "sources": json.loads(row["sources"]), "mode": row["mode"],
                 "product_id": row["product_id"]} for row in reversed(rows)]

    def append(self, token, question, result):
        with self.db() as db:
            db.execute("INSERT INTO qa_turns(session,question,answer,sources,mode,created,product_id) VALUES (%s,%s,%s,%s,%s,%s,%s)",
                       (self.digest(token), question, result["answer"], json.dumps(result["sources"], ensure_ascii=False),
                        result["mode"], time.time(), result.get("product_id")))
